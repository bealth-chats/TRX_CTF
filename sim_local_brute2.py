import numpy as np
import string

with open("flag_ct.txt", "rb") as f:
    data = f.read()

start = data.find(b'[')
end = data.rfind(b']') + 1
list_str = data[start:end].replace(b'np.complex128', b'complex')

ct = eval(list_str.decode('utf-8', errors='ignore'))
blocks = [ct[i*256 : (i+1)*256] for i in range(len(ct) // 256)]

flag_len = len(blocks)
flag = ['?'] * flag_len

known_map = {
    1: [8, 33], 4: [9, 30, 34], 5: [11, 25, 29], 7: [10, 19, 24, 32],
    12: [31, 35], 13: [23, 27], 14: [17, 22], 15: [28]
}

flag[0] = 'T'
flag[1] = 'R'
flag[2] = 'X'
flag[3] = '{'
flag[-1] = '}'

for k, v in known_map.items():
    if flag[k] != '?':
        for idx in v: flag[idx] = flag[k]

print("Initial flag:")
print("".join(flag))

